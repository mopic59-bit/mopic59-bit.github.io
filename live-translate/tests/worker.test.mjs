import test from 'node:test';import assert from 'node:assert/strict';
let handler,removed,stored={},tab=20;
globalThis.chrome={storage:{local:{get:async()=>structuredClone(stored),set:async o=>{stored=structuredClone(o);}}},tabs:{create:async()=>({id:++tab}),sendMessage:async()=>{},onRemoved:{addListener:fn=>removed=fn}},runtime:{onMessage:{addListener:fn=>handler=fn}}};
await import('../extension/worker.mjs');
const app={url:'https://mopic59-bit.github.io/live-translate/',tab:{id:1}},otherApp={...app,tab:{id:2}};
const call=(action,payload={},sender=app)=>new Promise(resolve=>handler({action,payload},sender,resolve));
test('worker lifecycle, sender checks, stale-session isolation and stop',async()=>{
 assert((await call('ping',{}, {url:'https://evil.example/',tab:{id:1}})).error);
 assert.equal((await call('ping')).version,'1.0.0');
 assert.equal((await call('start',{sessionId:'session-1',lang:'en'})).ok,true);
 const google={url:'https://translate.google.co.kr/',tab:{id:21}};
 assert.equal((await call('frame',{source:'Hello.',target:'안녕.',available:true},google)).capturing,true);
 assert.equal((await call('poll',{sessionId:'session-1'})).rows.length,1);
 assert((await call('start',{sessionId:'session-2'},otherApp)).error);
 await call('pause',{sessionId:'session-1'});
 assert.equal((await call('frame',{source:'paused'},google)).capturing,false);
 await call('resume',{sessionId:'session-1'});
 assert.equal((await call('stop',{sessionId:'session-1'})).rows.length,1);
 assert.equal((await call('frame',{source:'late'},google)).capturing,false);
 await call('start',{sessionId:'session-2',lang:'ja'});
 assert.equal((await call('frame',{source:'old tab'},google)).capturing,false);
 assert((await call('stop',{sessionId:'session-1'})).error);
 assert.equal((await call('poll',{sessionId:'session-2'})).rows.length,0);
 stored.active.lease=Date.now()-16000;
 assert.equal((await call('frame',{source:'expired'}, {url:'https://translate.google.co.kr/',tab:{id:22}})).capturing,false);
 await call('poll',{sessionId:'session-2'});
 removed(22); await new Promise(r=>setTimeout(r,10));
 assert.equal((await call('poll',{sessionId:'session-2'})).status,'stopped');
});
